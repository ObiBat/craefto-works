/**
 * A team member on a lit card (see .lit-card in globals.css): the photo comes
 * into colour and leans in when the card is hovered or, on phones, in the
 * middle of the screen.
 */
function TeamCard({ member }: { member: TeamMember }) {
  const [first, ...rest] = member.name.split(" ");
  const initials = member.name.split(" ").map((part) => part[0]).join("");

  return (
    <article className="lit-card flex h-full flex-col overflow-hidden rounded-3xl">
      <div className="relative m-2 aspect-[4/5] overflow-hidden rounded-[1.25rem] bg-[hsl(var(--color-background-muted))]">
        {member.image ? (
          <Image
            src={member.image}
            alt={member.name}
            fill
            className="team-photo object-cover"
            sizes="(max-width: 640px) 100vw, (max-width: 1024px) 50vw, 25vw"
          />
        ) : (
          <div className="absolute inset-0 grid place-items-center font-heading text-2xl font-semibold text-[hsl(var(--color-foreground-subtle))]">
            {initials}
          </div>
        )}
      </div>
      <div className="flex flex-1 flex-col px-5 pt-3 pb-5">
        <div className="flex items-start justify-between gap-3">
          <h3>
            <span className="lit-card-title block font-heading text-xl font-semibold tracking-tight">
              {first}
              {rest.length > 0 && <span className="font-normal text-[hsl(var(--color-foreground-muted))]"> {rest.join(" ")}</span>}
            </span>
          </h3>
          {member.socials.linkedin && (
            <a
              href={member.socials.linkedin}
              target="_blank"
              rel="noopener noreferrer"
              aria-label={`${member.name} on LinkedIn`}
              className="team-link grid size-9 shrink-0 place-items-center rounded-full bg-[hsl(var(--color-background))] text-[hsl(var(--color-accent))] transition-colors duration-300 hover:bg-[hsl(var(--color-accent))] hover:text-white"
            >
              <LinkedinLogo size={18} weight="duotone" aria-hidden="true" />
            </a>
          )}
        </div>
        <p className="mt-1 text-sm text-[hsl(var(--color-foreground-muted))]">{member.role}</p>
        <p className="mt-3 text-xs italic text-[hsl(var(--color-foreground-subtle))]">{member.detail}</p>
      </div>
    </article>
  );
}

